def _cookie_names(headers: object) -> str:
    try:
        raw = headers.get_list("set-cookie")  # type: ignore[attr-defined]
    except Exception:
        raw = []
    return " ".join(raw).lower()


def _match_fingerprints(headers: object, body: str) -> list[str]:
    header_names: dict[str, str] = {}
    try:
        header_names = {key.lower(): value.lower() for key, value in headers.items()}  # type: ignore[attr-defined]
    except Exception:
        pass
    cookies = _cookie_names(headers)
    body_lower = body[:300_000].lower()
    matches: list[str] = []
    for fingerprint in FINGERPRINTS:
        found = False
        for header, values in fingerprint.headers.items():
            current = header_names.get(header)
            if current is None:
                continue
            if not values or not any(values) or any(value in current for value in values if value):
                found = True
                break
        if not found and cookies and any(cookie in cookies for cookie in fingerprint.cookies):
            found = True
        if not found and body_lower and any(marker in body_lower for marker in fingerprint.body):
            found = True
        if found:
            matches.append(fingerprint.vendor)
    return sorted(set(matches))


def _looks_blocked(status: int, body: str, headers: object, baseline_status: int) -> bool:
    if baseline_status in (403, 406, 429):
        return False
    if status in (403, 406, 429, 503):
        haystack = body[:200_000].lower()
        return any(
            marker in haystack
            for marker in (
                "blocked",
                "access denied",
                "not acceptable",
                "security",
                "firewall",
                "request rejected",
                "forbidden",
            )
        )
    return False


async def run(
    target: str,
    *,
    aggressive: bool = False,
) -> list[Finding]:
    """Fingerprint a WAF using a clean request and conventional probe payloads."""
    url = ensure_url(target)
    param = next(iter(query_param_names(url)), "id")
    async with AsyncHTTPClient(module="waf", aggressive=aggressive) as client:
        try:
            baseline = await client.get(url, module="waf", timeout=20.0)
        except Exception as exc:
            raise RuntimeError(f"Baseline request failed: {type(exc).__name__}: {exc}") from exc
        baseline_body = baseline.text[:500_000]
        detected = set(_match_fingerprints(baseline.headers, baseline_body))
        blocked_variants = 0
        probe_details: list[str] = []
        generic_block = False
        for label, payload in PROBES:
            probe_url = append_query_param(url, param, payload)
            try:
                response = await client.get(probe_url, module="waf", timeout=20.0)
            except Exception as exc:
                probe_details.append(f"{label}: request failed ({type(exc).__name__})")
                continue
            body = response.text[:500_000]
            vendors = _match_fingerprints(response.headers, body)
            detected.update(vendors)
            if _looks_blocked(response.status_code, body, response.headers, baseline.status_code):
                blocked_variants += 1
                generic_block = True
            probe_details.append(
                f"{label}: HTTP {response.status_code}, {len(body)} bytes"
                + (f", fingerprint={', '.join(vendors)}" if vendors else "")
            )

    if detected:
        vendors = ", ".join(sorted(detected))
        finding = Finding(
            type="waf_detected",
            target=url,
            module="waf",
            url=url,
            evidence=(
                f"WAF/CDN fingerprint detected: {vendors}. Baseline HTTP {baseline.status_code}; "
                f"{blocked_variants}/{len(PROBES)} probes returned a block-like response."
            ),
            severity="info",
            confidence="high",
            metadata={
                "vendors": sorted(detected),
                "baseline_status": baseline.status_code,
                "blocked_probes": blocked_variants,
                "probes": probe_details,
                "note": "WAF presence is informational, not a vulnerability by itself.",
            },
        )
        return [finding]

    if blocked_variants >= 2:
        return [
            Finding(
                type="waf_suspected",
                target=url,
                module="waf",
                url=url,
                evidence=(
                    f"No vendor signature matched, but {blocked_variants}/{len(PROBES)} benign probes "
                    "produced block-like responses while the baseline did not. A WAF or restrictive "
                    "edge rule may be present."
                ),
                severity="info",
                confidence="medium",
                metadata={
                    "baseline_status": baseline.status_code,
                    "blocked_probes": blocked_variants,
                    "probes": probe_details,
                },
            )
        ]

    return [
        Finding(
            type="waf_not_detected",
            target=url,
            module="waf",
            url=url,
            evidence=(
                f"No known WAF fingerprint was found. Baseline HTTP {baseline.status_code}; "
                f"{blocked_variants}/{len(PROBES)} probes produced block-like responses."
            ),
            severity="info",
            confidence="medium",
            metadata={
                "baseline_status": baseline.status_code,
                "blocked_probes": blocked_variants,
                "probes": probe_details,
                "note": "Absence of a fingerprint does not prove absence of a WAF.",
            },
        )
    ]
